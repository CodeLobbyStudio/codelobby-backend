
CREATE TABLE tags (
                      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                      name VARCHAR(100) NOT NULL,
                      slug VARCHAR(100) NOT NULL,

                      CONSTRAINT uk_tags_name UNIQUE (name),
                      CONSTRAINT uk_tags_slug UNIQUE (slug)
);

CREATE TABLE tasks (
                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       catalog_number INTEGER,
                       title VARCHAR(200) NOT NULL,
                       description TEXT NOT NULL,
                       type VARCHAR(20) NOT NULL,
                       difficulty VARCHAR(20),
                       author_id BIGINT NOT NULL,
                       created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                       CONSTRAINT uk_tasks_catalog_number
                           UNIQUE (catalog_number),

                       CONSTRAINT fk_tasks_author
                           FOREIGN KEY (author_id)
                               REFERENCES app_users(id),

                       CONSTRAINT ck_tasks_type
                           CHECK (type IN ('OFFICIAL', 'CUSTOM')),

                       CONSTRAINT ck_tasks_difficulty
                           CHECK (
                               difficulty IS NULL
                                   OR difficulty IN ('EASY', 'MEDIUM', 'HARD')
                               ),

                       CONSTRAINT ck_tasks_catalog
                           CHECK (
                               (
                                   type = 'OFFICIAL'
                                       AND catalog_number IS NOT NULL
                                       AND catalog_number > 0
                                       AND difficulty IS NOT NULL
                                   )
                                   OR
                               (
                                   type = 'CUSTOM'
                                       AND catalog_number IS NULL
                                   )
                               )
);

CREATE TABLE task_tags (
                           task_id BIGINT NOT NULL,
                           tag_id BIGINT NOT NULL,

                           CONSTRAINT pk_task_tags
                               PRIMARY KEY (task_id, tag_id),

                           CONSTRAINT fk_task_tags_task
                               FOREIGN KEY (task_id)
                                   REFERENCES tasks(id)
                                   ON DELETE CASCADE,

                           CONSTRAINT fk_task_tags_tag
                               FOREIGN KEY (tag_id)
                                   REFERENCES tags(id)
);

CREATE TABLE task_languages (
                                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                task_id BIGINT NOT NULL,
                                language VARCHAR(20) NOT NULL,

                                CONSTRAINT fk_task_languages_task
                                    FOREIGN KEY (task_id)
                                        REFERENCES tasks(id)
                                        ON DELETE CASCADE,

                                CONSTRAINT uk_task_languages_task_language
                                    UNIQUE (task_id, language),

                                CONSTRAINT ck_task_languages_language
                                    CHECK (language IN ('JAVA', 'CPP', 'PYTHON'))
    );

CREATE TABLE task_files (
                            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            task_language_id BIGINT NOT NULL,
                            path VARCHAR(500) NOT NULL,
                            file_type VARCHAR(20) NOT NULL,
                            content TEXT NOT NULL,

                            CONSTRAINT fk_task_files_task_language
                                FOREIGN KEY (task_language_id)
                                    REFERENCES task_languages(id)
                                    ON DELETE CASCADE,

                            CONSTRAINT uk_task_files_language_path
                                UNIQUE (task_language_id, path),

                            CONSTRAINT ck_task_files_type
                                CHECK (
                                    file_type IN (
                                                  'EDITABLE',
                                                  'READ_ONLY',
                                                  'VISIBLE_TEST',
                                                  'HIDDEN_TEST'
                                        )
                                    ),

                            CONSTRAINT ck_task_files_path_not_empty
                                CHECK (length(trim(path)) > 0)
);

CREATE INDEX idx_tasks_author_id
    ON tasks(author_id);

CREATE INDEX idx_tasks_type_difficulty
    ON tasks(type, difficulty);

CREATE INDEX idx_task_tags_tag_id
    ON task_tags(tag_id);
