
CREATE TABLE lobby_members (
                               id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                               lobby_id BIGINT NOT NULL,
                               user_id BIGINT NOT NULL,

                               role VARCHAR(20) NOT NULL,

                               joined_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                               CONSTRAINT fk_lobby_members_lobby
                                   FOREIGN KEY (lobby_id)
                                       REFERENCES lobbies(id)
                                       ON DELETE CASCADE,

                               CONSTRAINT fk_lobby_members_user
                                   FOREIGN KEY (user_id)
                                       REFERENCES app_users(id),

                               CONSTRAINT uk_lobby_members_lobby_user
                                   UNIQUE (lobby_id, user_id),

                               CONSTRAINT ck_lobby_members_role
                                   CHECK (role IN ('HOST', 'PARTICIPANT'))
);

CREATE UNIQUE INDEX uk_lobby_members_single_host
    ON lobby_members (lobby_id)
    WHERE role = 'HOST';

CREATE INDEX idx_lobby_members_user_id
    ON lobby_members (user_id);

INSERT INTO lobby_members (lobby_id, user_id, role)
SELECT id, host_id, 'HOST'
FROM lobbies;
